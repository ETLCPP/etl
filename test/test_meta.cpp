  //---------------------------------------------------------------------------
  // Helper macros: evaluate consteval-only expressions at compile time,
  // then pass the plain bool/value result to the runtime CHECK framework.
  // GCC 16's std::meta::info is a consteval-only type and cannot appear
  // in runtime expressions such as those generated by CHECK().
  //---------------------------------------------------------------------------
  #define CONSTEXPR_CHECK(expr)          \
    do {                                 \
      constexpr bool _etl_chk_ = (expr); \
      CHECK(_etl_chk_);                  \
    } while (0)

  #define CONSTEXPR_CHECK_FALSE(expr)    \
    do {                                 \
      constexpr bool _etl_chk_ = (expr); \
      CHECK(!_etl_chk_);                 \
    } while (0)

  #define CONSTEXPR_CHECK_EQUAL(expected, expr) \
    do {                                        \
      constexpr auto _etl_val_ = (expr);        \
      CHECK_EQUAL(expected, _etl_val_);         \
    } while (0)

